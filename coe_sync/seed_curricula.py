def ensure_curriculum_master_data():
    """
    Ensure all required curriculum subjects and official curricula are populated in the database.
    Safe and idempotent.
    """
    # 1. Insert any missing subjects needed by official curricula
    existing_subjects = {s.code: s for s in Subject.query.all()}
    for meta in ADDITIONAL_CURRICULUM_SUBJECTS:
        code = meta["code"]
        if code not in existing_subjects:
            new_sub = Subject(
                code=code,
                title=meta["title"],
                program=meta["program"],
                units=meta["units"],
                hours_per_week=meta["hours_per_week"],
                subject_type=meta["subject_type"],
                year_level=meta.get("year_level", 1),
                semester=meta.get("semester", 1),
                split_preference="3_HOUR_BLOCK",
                is_general=(meta["program"] == "GEN"),
                requires_grouping=(meta["subject_type"] == "LAB"),
                preferred_session_type="STRAIGHT",
            )
            db.session.add(new_sub)
            db.session.flush()
            existing_subjects[code] = new_sub

    # Refresh subject map
    all_subjects = {s.code: s for s in Subject.query.all()}

    # 2. Populate / Update Curricula
    for curr_info in CURRICULA_METADATA:
        code = curr_info["code"]
        curr = Curriculum.query.filter_by(code=code).first()
        if not curr:
            curr = Curriculum(
                code=code,
                name=curr_info["name"],
                program=curr_info["program"],
                revision_year=curr_info.get("revision_year"),
                cmo_reference=curr_info.get("cmo_reference"),
                is_active=True,
            )
            db.session.add(curr)
            db.session.flush()
        else:
            # Update name if changed (e.g. to match uploaded file name)
            curr.name = curr_info["name"]
            curr.program = curr_info["program"]
            curr.revision_year = curr_info.get("revision_year")
            curr.cmo_reference = curr_info.get("cmo_reference")
            curr.is_active = True
            db.session.flush()

        # If explicit mappings provided, populate CurriculumSubject
        mappings = curr_info.get("mappings")
        if mappings:
            # Check existing mappings
            existing_sub_ids = {cs.subject_id for cs in curr.curriculum_subjects}
            for scode, yr, sem, prereq, coreq in mappings:
                sub = all_subjects.get(scode)
                if not sub:
                    # Try with or without trailing L
                    sub = all_subjects.get(scode + "L") or all_subjects.get(scode.rstrip("L"))
                if sub and sub.id not in existing_sub_ids:
                    cs = CurriculumSubject(
                        curriculum_id=curr.id,
                        subject_id=sub.id,
                        year_level=yr,
                        semester=sem,
                        prerequisites=prereq,
                        corequisites=coreq,
                    )
                    db.session.add(cs)
                    existing_sub_ids.add(sub.id)
        else:
            # Department curriculum without custom PDF: map all existing subjects belonging to this program
            existing_sub_ids = {cs.subject_id for cs in curr.curriculum_subjects}
            prog_subs = [s for s in all_subjects.values() if s.program == curr.program]
            for s in prog_subs:
                if s.id not in existing_sub_ids:
                    cs = CurriculumSubject(
                        curriculum_id=curr.id,
                        subject_id=s.id,
                        year_level=s.year_level or 1,
                        semester=s.semester or 1,
                        prerequisites="",
                        corequisites="",
                    )
                    db.session.add(cs)
                    existing_sub_ids.add(s.id)

    db.session.commit()
    print("[COE SYNC 2026] Curriculum Master Data successfully synchronized.")
